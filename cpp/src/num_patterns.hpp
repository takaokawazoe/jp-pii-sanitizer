// 番号系（電話・郵便番号）の正規表現。**ここが唯一の定義。**
//
// **なぜ 1 箇所にまとめたか**: 同じ正規表現がソース 5 箇所（tokenizer に 3・step5・eval）と
// models/patterns.json に散っていた。1 つ直しても他が古いままになる形で、全角対応が
// 漏れていたときも全部を直す必要があった。
//
// **なぜ patterns.json を読まないか**: あのファイルは models-assets.zip（モデル束）に
// 同梱して配布している。リポジトリ側を直しても、CI の `fetch_assets.sh` が `unzip -o` で
// cpp/models を上書きするため、束を再アップロードするまで古い定義に戻る。
// 「手元では直っているが CI では直っていない」を作らないよう、番号系はソースを正とする。
#pragma once

#include <string>

namespace numpat {

// PCRE2 は PCRE2_UTF | PCRE2_UCP で動かしている（re.hpp）ので **`\d` は全角数字にも当たる**。
// 実測: `１５０-０００１` は元の `\d{3}-\d{4}` でもマスクされていた。詰まっていたのは
// **リテラル**の方だけ——`0` は `０` に当たらず、`-` は `－` に当たらない。
//
//   ０３-１２３４-５６７８   → 先頭の 0 で外れていた
//   150－0001               → 区切りで外れていた
//
// なので数字クラスは `\d` のままでよく、直すのは「0」と「区切り」。

namespace detail {
/// 区切りに使われうる文字。半角/全角のハイフンに加え、ワープロが混ぜてくる各種ダッシュと
/// 空白（全角空白 U+3000 を含む）。**`ー`（長音符 U+30FC）は入れない**——カタカナ語を割るため。
inline const std::string SEP = R"([-－‐‑−–— 　])";
/// ハイフン系のみ。郵便番号に使う（`150 0001` のような空白区切りは他のデータと紛れる）。
inline const std::string DASH = R"([-－‐‑−–—])";
}  // namespace detail

/// 電話番号。対応する書き方（いずれも実在する）:
///
///   03-1234-5678 / ０３－１２３４－５６７８ / 03(1234)5678 / 03 1234 5678 / 0312345678
///   +81-3-1234-5678（国番号。先頭の 0 が落ちるので別枝）
///
/// **区切りの混在は許す**（`03-1234 5678` のような雑な表記が実際にある）。後方参照で
/// 揃える手もあるが、取りこぼすより過剰に拾う方が安全側。
///
/// **既知の過剰マスク**: 空白区切りを許した副作用で、`0123 4567 8901` のような 12 桁の
/// 数字コードも電話として拾う。README が「この形の番号は常に自動でマスクする」と
/// 宣言している範囲なので、取りこぼす側には倒さない。
inline const std::string PHONE =
    R"((?<![\d\-－])(?:[+＋]81)" + detail::SEP + R"(?\d{1,4})" + detail::SEP + R"(\d{1,4})" +
    detail::SEP + R"(\d{3,4}|[0０]\d{1,4})" + detail::SEP + R"(\d{1,4})" + detail::SEP +
    R"(\d{3,4}|[0０]\d{1,4}[(（]\d{1,4}[)）]\d{3,4}|[0０]\d{9,10})(?![\d\-－]))";

/// 郵便番号（`150-0001` / `１５０－０００１`）。
inline const std::string POSTAL =
    R"((?<![\d\-－])\d{3})" + detail::DASH + R"(\d{4}(?![\d\-－]))";

}  // namespace numpat
